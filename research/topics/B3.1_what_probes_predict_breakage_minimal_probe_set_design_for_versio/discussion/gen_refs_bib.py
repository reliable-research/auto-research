#!/usr/bin/env python3
"""Script-generate refs.bib from reference_candidates.jsonl's `selected` records.

Per goal.md Phase E-F discipline: "refs.bib script-generated from the jsonl's
selected entries" -- never hand-typed. Re-run this script any time the jsonl's
selected set changes; it deterministically overwrites refs.bib.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
JSONL = HERE / "reference_candidates.jsonl"
OUT = HERE / "refs.bib"


def bibkey(key: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", key)


def escape(s: str) -> str:
    return s.replace("&", r"\&").replace("_", r"\_").replace("%", r"\%")


def make_entry(r: dict) -> str:
    key = bibkey(r["key"])
    title = escape(r.get("title", "").strip())
    year = r.get("year")
    venue = r.get("venue", "") or ""
    arxiv = (r.get("ids") or {}).get("arxiv")
    doi = (r.get("ids") or {}).get("doi")
    openreview = (r.get("ids") or {}).get("openreview")
    url = r.get("url", "")

    fields = [f'  title = {{{title}}}']
    if year:
        fields.append(f"  year = {{{year}}}")
    else:
        fields.append("  year = {n.d.}")

    if arxiv:
        fields.append(f"  eprint = {{{arxiv}}}")
        fields.append("  archivePrefix = {arXiv}")
        entry_type = "misc"
        note_bits = ["arXiv:" + arxiv]
    elif doi:
        fields.append(f"  doi = {{{doi}}}")
        entry_type = "inproceedings" if "ACL" in venue or "acl" in venue else "misc"
        note_bits = [venue] if venue else []
    elif openreview:
        entry_type = "misc"
        note_bits = [f"OpenReview:{openreview}"]
    else:
        entry_type = "misc"
        note_bits = [venue] if venue else []

    if url:
        fields.append(f"  url = {{{url}}}")

    clean_venue = escape(venue) if venue else ""
    if clean_venue and clean_venue not in " ".join(note_bits):
        note_bits.append(clean_venue)
    if note_bits:
        fields.append(f"  note = {{{escape(' -- '.join(note_bits))}}}")

    body = ",\n".join(fields)
    return f"@{entry_type}{{{key},\n{body}\n}}"


def main():
    if not JSONL.exists():
        print(f"missing {JSONL}", file=sys.stderr)
        sys.exit(1)

    selected = []
    with JSONL.open() as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            if r.get("verdict") == "selected":
                selected.append(r)

    selected.sort(key=lambda r: r["key"])

    header = (
        "% AUTO-GENERATED by discussion/gen_refs_bib.py -- do not hand-edit.\n"
        "% Source of truth: discussion/reference_candidates.jsonl (`selected` records only).\n"
        f"% Regenerate with: python3 discussion/gen_refs_bib.py\n"
        f"% {len(selected)} selected records at generation time.\n\n"
    )
    entries = "\n\n".join(make_entry(r) for r in selected)
    OUT.write_text(header + entries + "\n")
    print(f"wrote {OUT} with {len(selected)} entries")


if __name__ == "__main__":
    main()
