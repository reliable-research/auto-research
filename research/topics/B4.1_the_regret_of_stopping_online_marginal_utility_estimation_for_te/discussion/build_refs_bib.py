#!/usr/bin/env python3
"""Script-generate refs.bib from reference_candidates.jsonl's `selected` records.

Per goal.md Phase F: "refs.bib script-generated from the jsonl; results tables
script-generated from results/*.json -- hand-typing either is banned." This
script is the canonical generator; re-run it whenever reference_candidates.jsonl
changes rather than hand-editing refs.bib.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSONL = HERE / "reference_candidates.jsonl"
OUT = HERE / "refs.bib"


def bibkey(key: str) -> str:
    """Bib citation key = the jsonl record's own `key` field, sanitized."""
    return re.sub(r"[^A-Za-z0-9_]", "", key)


def guess_author_field(rec) -> str:
    # No structured author list is stored in the cache; use a placeholder
    # organization/anonymous field consistent with each record's own venue
    # framing (OpenReview double-blind submissions are anonymous by design).
    venue = (rec.get("venue") or "").lower()
    if "openreview" in venue:
        return "{Anonymous}"
    return "{Unknown}"


def make_entry(rec) -> str:
    key = bibkey(rec["key"])
    title = rec.get("title", "").replace("{", "").replace("}", "")
    year = rec.get("year", "")
    venue = rec.get("venue", "") or ""
    url = rec.get("url", "") or ""
    ids = rec.get("ids", {}) or {}
    arxiv_id = ids.get("arxiv")
    author = guess_author_field(rec)

    if arxiv_id:
        return (
            f"@article{{{key},\n"
            f"  title   = {{{{{title}}}}},\n"
            f"  author  = {author},\n"
            f"  journal = {{arXiv preprint arXiv:{arxiv_id}}},\n"
            f"  year    = {{{year}}},\n"
            f"  url     = {{https://arxiv.org/abs/{arxiv_id}}}\n"
            f"}}\n"
        )
    elif "openreview" in venue.lower() or ids.get("openreview"):
        oid = ids.get("openreview", "")
        return (
            f"@misc{{{key},\n"
            f"  title        = {{{{{title}}}}},\n"
            f"  author       = {author},\n"
            f"  howpublished = {{OpenReview submission {oid}}},\n"
            f"  year         = {{{year}}},\n"
            f"  url          = {{{url or f'https://openreview.net/forum?id={oid}'}}}\n"
            f"}}\n"
        )
    elif "acl" in venue.lower():
        return (
            f"@inproceedings{{{key},\n"
            f"  title     = {{{{{title}}}}},\n"
            f"  author    = {author},\n"
            f"  booktitle = {{{venue}}},\n"
            f"  year      = {{{year}}},\n"
            f"  url       = {{{url}}}\n"
            f"}}\n"
        )
    else:
        return (
            f"@misc{{{key},\n"
            f"  title        = {{{{{title}}}}},\n"
            f"  author       = {author},\n"
            f"  howpublished = {{{venue}}},\n"
            f"  year         = {{{year}}},\n"
            f"  url          = {{{url}}}\n"
            f"}}\n"
        )


def main():
    recs = [json.loads(l) for l in JSONL.open() if l.strip()]
    selected = [r for r in recs if r.get("verdict") == "selected"]
    entries = [make_entry(r) for r in selected]
    header = (
        "% AUTO-GENERATED by build_refs_bib.py from reference_candidates.jsonl.\n"
        "% Do not hand-edit -- re-run the script after updating the jsonl's\n"
        "% `selected` records. Generated for topic B4.1.\n\n"
    )
    OUT.write_text(header + "\n".join(entries))
    print(f"Wrote {len(entries)} entries to {OUT}")


if __name__ == "__main__":
    main()
