#!/usr/bin/env python3
"""Generate refs.bib from reference_candidates.jsonl (goal.md section 6/8:
refs.bib is script-generated from the cache, never hand-typed).

Rules:
- only verdict == "selected" records are emitted;
- title_status != "verified" records get an explanatory bibtex note so no
  descriptive/scan-recorded title can be mistaken for a verbatim one;
- entries are sorted by key for stable diffs.
"""
import json, pathlib

SRC = pathlib.Path(__file__).parent / "reference_candidates.jsonl"
DST = pathlib.Path(__file__).parent / "refs.bib"

STATUS_NOTE = {
    "as-recorded-in-scan": "Title as recorded in the local 2026-08 corpus scan.",
    "descriptive-not-cached": "Descriptive title; the local corpus scan records this entry only by arXiv identifier, scale, and no-trace-release status.",
    "system-name-only": "Cited by system name and arXiv identifier as recorded in the 2026-08 corpus scan; full title not cached locally.",
}


def bib_author(authors):
    return " and ".join("others" if a == "others" else a for a in authors)


def entry(rec):
    key = rec["key"]
    arxiv = rec.get("ids", {}).get("arxiv")
    venue = rec.get("venue", "arXiv")
    fields = {
        "author": bib_author(rec.get("authors", ["Anonymous"])),
        "title": "{" + rec["title"] + "}",
        "year": str(rec["year"]),
    }
    notes = []
    if venue and venue != "arXiv":
        fields["booktitle"] = venue
        kind = "inproceedings"
        if arxiv:
            notes.append(f"arXiv:{arxiv}")
    else:
        kind = "misc"
        if arxiv:
            fields["eprint"] = arxiv
            fields["archiveprefix"] = "arXiv"
    status = rec.get("title_status", "verified")
    if status in STATUS_NOTE:
        notes.append(STATUS_NOTE[status])
    if notes:
        fields["note"] = " ".join(notes)
    body = ",\n".join(f"  {k} = {{{v}}}" if not v.startswith("{") else f"  {k} = {v}"
                      for k, v in fields.items())
    return f"@{kind}{{{key},\n{body}\n}}\n"


def main():
    recs = [json.loads(l) for l in SRC.read_text().splitlines() if l.strip()]
    sel = sorted((r for r in recs if r.get("verdict") == "selected"), key=lambda r: r["key"])
    DST.write_text("% Generated by gen_refs_bib.py from reference_candidates.jsonl -- do not hand-edit.\n\n"
                   + "\n".join(entry(r) for r in sel))
    print(f"wrote {DST.name}: {len(sel)} entries")


if __name__ == "__main__":
    main()
