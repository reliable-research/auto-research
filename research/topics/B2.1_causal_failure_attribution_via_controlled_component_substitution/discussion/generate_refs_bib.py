#!/usr/bin/env python3
"""Generate discussion/refs.bib from discussion/reference_candidates.jsonl's
`selected` records. Per goal.md Phase F: "refs.bib script-generated from the
jsonl's selected records — hand-typing either is banned." Re-run this script
whenever reference_candidates.jsonl's selected set changes; do not hand-edit
refs.bib.

Only the 10 records actually cited in paper_draft.tex (via \\cite{<key>}) are
emitted here (WhoAndWhen2025, WhoAndWhenPro2026, DoVer2025, AgenTracer2025,
SelfEvolveBench2025, TerminalBench2025, AutoLibra2025, CRM2025, FAPO2025,
Defects4J2014) — i.e.
every `selected` record with relevance in {baseline, method-twin, contrast,
background} that Related Work / Experimental Setup prose actually names.
`adjacent`/`rejected` records (including the three freshness-sweep rejects
logged 2026-07-04) are not cited and are correctly excluded.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSONL_PATH = HERE / "reference_candidates.jsonl"
BIB_PATH = HERE / "refs.bib"

# Keys actually cited in paper_draft.tex/.md prose (kept explicit, not just
# "all selected", so refs.bib doesn't silently balloon with non-cited cache
# entries such as the 7 background-tier B2.1-unrelated selections).
CITED_KEYS = [
    "WhoAndWhen2025",
    "WhoAndWhenPro2026",
    "DoVer2025",
    "AgenTracer2025",
    "SelfEvolveBench2025",
    "TerminalBench2025",
    "AutoLibra2025",
    "CRM2025",
    "FAPO2025",
    "Defects4J2014",
]


def load_selected(jsonl_path):
    records = {}
    with open(jsonl_path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            if rec.get("verdict") == "selected":
                records[rec["key"]] = rec
    return records


def escape_bib(s):
    if s is None:
        return ""
    return s.replace("&", "\\&").replace("_", "\\_")


def bib_entry(rec):
    key = rec["key"]
    title = escape_bib(rec.get("title", ""))
    authors = rec.get("authors_bib", "Anonymous")
    year = rec.get("year", "")
    venue = escape_bib(rec.get("venue", ""))
    url = rec.get("url", "")
    ids = rec.get("ids", {}) or {}
    arxiv = ids.get("arxiv")
    doi = ids.get("doi")
    openreview = ids.get("openreview")

    fields = [
        f'  author    = {{{authors}}}',
        f'  title     = {{{title}}}',
        f'  year      = {{{year}}}',
    ]
    if venue:
        fields.append(f'  booktitle = {{{venue}}}' if "Proceedings" in venue or "ICLR" in venue or "ISSTA" in venue else f'  howpublished = {{{venue}}}')
    if arxiv:
        fields.append(f'  eprint    = {{{arxiv}}}')
        fields.append('  archivePrefix = {arXiv}')
    if doi:
        fields.append(f'  doi       = {{{doi}}}')
    if openreview and not arxiv:
        fields.append(f'  note      = {{OpenReview: {openreview}}}')
    if url:
        fields.append(f'  url       = {{{url}}}')

    entrytype = "inproceedings" if ("Proceedings" in venue or "ICLR" in venue or "ISSTA" in venue) else "misc"
    body = ",\n".join(fields)
    return f"@{entrytype}{{{key},\n{body}\n}}\n"


def main():
    records = load_selected(JSONL_PATH)
    missing = [k for k in CITED_KEYS if k not in records]
    if missing:
        print(f"ERROR: cited keys missing from selected cache: {missing}", file=sys.stderr)
        sys.exit(1)

    entries = [bib_entry(records[k]) for k in CITED_KEYS]
    BIB_PATH.write_text("% Auto-generated by generate_refs_bib.py from reference_candidates.jsonl.\n"
                         "% Do not hand-edit; re-run the script after updating the jsonl's selected set.\n\n"
                         + "\n".join(entries))
    print(f"Wrote {len(entries)} entries to {BIB_PATH}")


if __name__ == "__main__":
    main()
