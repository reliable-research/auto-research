#!/usr/bin/env python3
"""Generate refs.bib from reference_candidates.jsonl's `selected` records.

Per goal.md Phase F: "refs.bib is generated from this file (scripted), never
hand-typed." Run from the `discussion/` directory:
    python3 gen_refs_bib.py
"""
import json
import re

IN_JSONL = "reference_candidates.jsonl"
OUT_BIB = "refs.bib"


def guess_year(record):
    if record.get("year"):
        return record["year"]
    arxiv_id = (record.get("ids") or {}).get("arxiv")
    if arxiv_id and re.match(r"^\d{4}\.\d+", arxiv_id):
        yy = int(arxiv_id[:2])
        return 2000 + yy
    return "n.d."


def venue_field(record):
    venue = record.get("venue") or "arXiv"
    arxiv_id = (record.get("ids") or {}).get("arxiv")
    if venue == "arXiv" and arxiv_id:
        return f"  journal = {{arXiv preprint arXiv:{arxiv_id}}},\n"
    if record.get("ids", {}).get("doi"):
        return f"  journal = {{{venue}}},\n  doi = {{{record['ids']['doi']}}},\n"
    return f"  journal = {{{venue}}},\n"


def make_entry(record):
    key = record["key"]
    title = record["title"].replace("{", "").replace("}", "")
    authors = record.get("authors", "Unknown Author")
    year = guess_year(record)
    url = record.get("url", "")
    entry = [f"@misc{{{key},"]
    entry.append(f"  title = {{{title}}},")
    entry.append(f"  author = {{{authors}}},")
    entry.append(f"  year = {{{year}}},")
    v = venue_field(record).rstrip(",\n")
    entry.append(v.strip() + ",")
    if url:
        entry.append(f"  url = {{{url}}},")
    entry.append("}")
    return "\n".join(entry)


def main():
    selected = []
    with open(IN_JSONL) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            if d.get("verdict") == "selected":
                selected.append(d)

    selected.sort(key=lambda d: d["key"])

    with open(OUT_BIB, "w") as f:
        f.write(
            "% Auto-generated by gen_refs_bib.py from reference_candidates.jsonl's\n"
            "% `selected` records. Do not hand-edit; re-run the script instead.\n\n"
        )
        for d in selected:
            f.write(make_entry(d))
            f.write("\n\n")

    print(f"Wrote {len(selected)} entries to {OUT_BIB}")


if __name__ == "__main__":
    main()
